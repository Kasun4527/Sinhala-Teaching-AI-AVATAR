// Helper: find subject data across all grades
export function findSubject(subjectName) {
  for (const grade of curriculum) {
    const found = grade.subjects.find((s) => s.subject === subjectName);
    if (found) return found;
  }
  return null;
}

// Helper: find subject within a specific grade
export function findSubjectByGrade(subjectName, gradeName) {
  const grade = curriculum.find((g) => g.grade === gradeName);
  if (!grade) return null;
  return grade.subjects.find((s) => s.subject === subjectName) || null;
}

// Helper: get all subjects flat list with grade info
export function getAllSubjects() {
  return curriculum.flatMap((grade) =>
    grade.subjects.map((s) => ({ ...s, grade: grade.grade }))
  );
}
